import { useMemo } from 'react'
import {
  Brush,
  CartesianGrid,
  Line,
  LineChart,
  ReferenceArea,
  ReferenceLine,
  ResponsiveContainer,
  Tooltip,
  XAxis,
  YAxis,
} from 'recharts'

const statusColors = {
  ok: '#22c55e',
  warning: '#f59e0b',
  violation: '#ef4444',
}

const statusLabels = {
  ok: 'In control',
  warning: 'Warning',
  violation: 'Out of control',
}

const axisTick = { fontSize: 11, fill: '#9ca3af' }

const formatDay = (iso) =>
  new Date(iso).toLocaleDateString('en-GB', { day: 'numeric', month: 'short' })

function StatusDot({ cx, cy, payload }) {
  if (cx === null || cy === null) return null
  const isOk = payload.status === 'ok'
  return (
    <circle
      cx={cx}
      cy={cy}
      r={isOk ? 3 : 5}
      fill={statusColors[payload.status]}
      stroke="#ffffff"
      strokeWidth={1.5}
    />
  )
}

function ChartTooltip({ active, payload, limits, sigma, unit }) {
  if (!active || !payload?.length) return null
  const point = payload[0].payload
  const z = (point.value - limits.mean) / sigma

  return (
    <div className="rounded-md border border-gray-200 bg-white px-3 py-2 text-xs shadow-sm">
      <div className="text-gray-500">{formatDay(point.date)}</div>
      <div className="mt-0.5 text-sm font-semibold text-gray-900">
        {point.value.toFixed(3)} {unit}
      </div>
      <div className="mt-1 flex items-center gap-1.5">
        <span
          className="h-2 w-2 rounded-full"
          style={{ backgroundColor: statusColors[point.status] }}
        />
        <span className="text-gray-700">{statusLabels[point.status]}</span>
        <span className="text-gray-400">
          ({z >= 0 ? '+' : ''}
          {z.toFixed(1)}σ)
        </span>
      </div>
    </div>
  )
}

export default function ControlChart({ data, title = 'Control chart', unit = '' }) {
  const { points, limits } = data
  const sigma = (limits.ucl - limits.mean) / 3

  const domain = useMemo(() => {
    const values = points.map((p) => p.value)
    const min = Math.min(limits.lcl, ...values)
    const max = Math.max(limits.ucl, ...values)
    return [min - sigma * 0.5, max + sigma * 0.5]
  }, [points, limits, sigma])

  const counts = useMemo(
    () =>
      points.reduce((acc, p) => {
        acc[p.status] = (acc[p.status] ?? 0) + 1
        return acc
      }, {}),
    [points]
  )

  const referenceLines = [
    { y: limits.ucl, label: 'UCL', color: statusColors.violation, dashed: true },
    { y: limits.uwl, label: 'UWL', color: statusColors.warning, dashed: true },
    { y: limits.mean, label: 'Mean', color: '#6b7280', dashed: false },
    { y: limits.lwl, label: 'LWL', color: statusColors.warning, dashed: true },
    { y: limits.lcl, label: 'LCL', color: statusColors.violation, dashed: true },
  ]

  return (
    <section className="rounded-lg border border-gray-200 bg-white p-4">
      <header className="mb-3 flex flex-wrap items-start justify-between gap-3">
        <div>
          <h3 className="text-sm font-semibold text-gray-900">{title}</h3>
          <p className="text-xs text-gray-500">
            Mean {limits.mean.toFixed(3)} · σ {sigma.toFixed(3)} · {points.length} checks
          </p>
        </div>
        <div className="flex flex-wrap items-center gap-3 text-xs text-gray-600">
          {Object.keys(statusColors).map((key) => (
            <span key={key} className="flex items-center gap-1.5">
              <span
                className="h-2 w-2 rounded-full"
                style={{ backgroundColor: statusColors[key] }}
              />
              {statusLabels[key]}
              <span className="font-medium text-gray-900">{counts[key] ?? 0}</span>
            </span>
          ))}
        </div>
      </header>

      <div className="h-80 min-w-0">
        <ResponsiveContainer
          width="100%"
          height="100%"
          minWidth={0}
          initialDimension={{ width: 320, height: 320 }}
        >
          <LineChart data={points} margin={{ top: 8, right: 44, bottom: 0, left: 0 }}>
            <ReferenceArea
              y1={limits.lwl}
              y2={limits.uwl}
              fill={statusColors.ok}
              fillOpacity={0.06}
            />
            <ReferenceArea
              y1={limits.uwl}
              y2={limits.ucl}
              fill={statusColors.warning}
              fillOpacity={0.08}
            />
            <ReferenceArea
              y1={limits.lcl}
              y2={limits.lwl}
              fill={statusColors.warning}
              fillOpacity={0.08}
            />

            <CartesianGrid stroke="#f3f4f6" vertical={false} />

            <XAxis
              dataKey="date"
              tickFormatter={formatDay}
              tick={axisTick}
              tickLine={false}
              axisLine={{ stroke: '#e5e7eb' }}
              minTickGap={24}
            />
            <YAxis
              domain={domain}
              tickFormatter={(v) => v.toFixed(2)}
              tick={axisTick}
              tickLine={false}
              axisLine={false}
              width={48}
            />

            {referenceLines.map(({ y, label, color, dashed }) => (
              <ReferenceLine
                key={label}
                y={y}
                stroke={color}
                strokeWidth={1}
                strokeDasharray={dashed ? '4 4' : undefined}
                label={{ value: label, position: 'right', fontSize: 10, fill: color }}
              />
            ))}

            <Tooltip
              content={<ChartTooltip limits={limits} sigma={sigma} unit={unit} />}
              cursor={{ stroke: '#d1d5db', strokeDasharray: '3 3' }}
            />

            <Line
              type="linear"
              dataKey="value"
              stroke="#374151"
              strokeWidth={1.5}
              dot={(props) => <StatusDot key={props.index} {...props} />}
              activeDot={{ r: 6, fill: '#111827', stroke: '#ffffff', strokeWidth: 2 }}
              isAnimationActive={false}
            />

            <Brush
              dataKey="date"
              height={24}
              stroke="#9ca3af"
              travellerWidth={8}
              tickFormatter={formatDay}
            />
          </LineChart>
        </ResponsiveContainer>
      </div>
    </section>
  )
}
